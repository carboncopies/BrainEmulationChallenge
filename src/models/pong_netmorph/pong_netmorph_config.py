"""pong_netmorph_config.py: writes the Netmorph config `nesvbp-pong`.

Physics, growth and synapse blocks are copied verbatim from the BEC reference
xor_scnm/nesvbp-xor-res-sep-targets (so the growth physics are the validated ones);
the regions and the chemical-attraction block are generated from pong_spec.

Usage: python pong_netmorph_config.py [-variant edge|class] [-out nesvbp-pong]
"""
import argparse
import os
import pong_spec as S

HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.join(HERE, '..', 'xor_scnm', 'nesvbp-xor-res-sep-targets')

HEADER = """# nesvbp-pong: Netmorph-grown version of the step-1 hand-wired Pong controller.
# GENERATED by pong_netmorph_config.py (variant=%(variant)s); edit the generator, not this file.
#
# Every functional role (B0-7 ball-y place cells, P0-7 paddle-y place cells,
# U0-7 / D0-7 comparators, UP, DOWN) is its own ONE-NEURON region named after the role.
# Netmorph has no per-neuron coordinates; a one-neuron disc of radius 8 um at a chosen
# centre is the closest we can get, and the region name then identifies the role in
# the abstract connectome ('Regions') with no ID guessing.
#
# Layout (um, defaults; see pong_spec.layout and -ystep/-xstage): x = stage (B/P at 0, U/D at X_STAGE,
# UP/DOWN at 2*X_STAGE), y = Y_STEP * bin,
# z = -250 (ball/U/UP row) or -450 (paddle/D/DOWN row). z stays < 0 because the 'pia'
# boundary below is a sphere of radius 50 mm centred at z=-50000.
# P cells: p_type=%(ptype)s. With 'interneuron' Netmorph makes their synapses GABA (default
# possible_syntypes: interneuron->anything is GABAR only; pyramidal->pyramidal is AMPAR + 0.4 NMDAR), which
# reproduces the step-1 inhibitory spec but cannot be strengthened afterwards (README). With 'pyramidal' the
# P cells excite and the comparators work as B AND P coincidence detectors (pong_spec.edges(paddle='ampa')).
# D_synmax (um) = %(dsyn)g for the pyramidal/interneuron type pairs.
#
# Steering: detailed_chemical_factors with neuron_specific_attraction_switch and
# single_attractor_per_growthcone. See the generated block 'CHEMICAL ATTRACTION'.

days=20;
dt=100;
randomseed=20241104;
enable_completion_requirements=false;

"""


def ref_lines():
    L = open(REF).read().split('\n')
    # 1-based line numbers from the reference: soma init 24-55, physics..axon dm 121-188, rest 203-end
    return L[23:55], L[120:188], L[202:]


def regions_block(variant, p_type):
    pos = S.layout()
    names = S.roles()
    out = ['# SOMA PLACEMENT PARAMETERS', 'shape=regions;', 'regions=%s;' % ' '.join(names), '']
    for r in names:
        x, y, z = pos[r]
        typ = 'interneuron' if (r[0] == 'P' and r != 'UP' and p_type == 'interneuron') else 'pyramidal'
        out += ['%s.shape=disc;' % r, '%s.neurons=0;' % r,
                '%s.pyramidal=%d;' % (r, 1 if typ == 'pyramidal' else 0),
                '%s.interneuron=%d;' % (r, 1 if typ == 'interneuron' else 0),
                '%s.minneuronseparation=5;' % r,
                '%s.centerX=%g;' % (r, x), '%s.centerY=%g;' % (r, y), '%s.centerZ=%g;' % (r, z),
                '%s.shape.radius=8;' % r, '%s.shape.thickness=8;' % r]
    return out + ['']


def attraction_block(variant, paddle='gaba'):
    """Region-level attractors (each region has one neuron).
    edge : one unique chemical per intended edge; the post neuron emits it and the
           pre neuron is attracted to it (neuron-specific attractors force pairs).
    class: one chemical per postsynaptic ROLE CLASS (no per-edge info), plus the spatial layout:
           B_i attracted to NGF_U and NGF_D, P_j to NGF_U and NGF_D, U_i to NGF_UP, D_i to NGF_DOWN.
    """
    emits, attr = {}, {}
    if variant == 'edge':
        for k, (cls, pre, post, sg) in enumerate(S.edges(paddle=paddle)):
            f = 'NGF_E%d' % k
            emits.setdefault(post, []).append(f)
            attr.setdefault(pre, []).append(f)
    elif variant == 'class':
        for r in S.roles():
            c = S.role_class(r)
            if c in ('U', 'D', 'UP', 'DOWN'):
                emits.setdefault(r, []).append('NGF_' + c)
        for r in S.roles():
            c = S.role_class(r)
            if c in ('B', 'P'):
                attr[r] = ['NGF_U', 'NGF_D']
            elif c == 'U':
                attr[r] = ['NGF_UP']
            elif c == 'D':
                attr[r] = ['NGF_DOWN']
    else:
        raise ValueError(variant)
    out = ['# CHEMICAL ATTRACTION (generated, variant=%s)' % variant,
           'detailed_chemical_factors=true;', 'soma_attraction_weight=0.0;', '']
    for r in S.roles():
        if r in emits:
            out.append('%s.attractors=%s;' % (r, ' '.join(emits[r])))
        if r in attr:
            out.append('%s.attractedto=%s;' % (r, ' '.join(attr[r])))
    return out + ['']


def make(variant='edge', p_type='interneuron', dsyn=2.0, ystep=None, xstage=None):
    if ystep is not None:
        S.Y_STEP = ystep
    if xstage is not None:
        S.X_STAGE = xstage
    soma, physics, rest = ref_lines()
    lines = (HEADER % dict(variant=variant, ptype=p_type, dsyn=dsyn)).split('\n') + soma + regions_block(variant, p_type) + \
        physics + attraction_block(variant, 'gaba' if p_type == 'interneuron' else 'ampa') + rest
    text = '\n'.join(lines)
    for pre, post in (('pyramidal', 'pyramidal'), ('pyramidal', 'interneuron'), ('interneuron', 'pyramidal')):
        text = text.replace('D_synmax.%s.%s=2.0;' % (pre, post), 'D_synmax.%s.%s=%g;' % (pre, post, dsyn))
    return text


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('-variant', default='edge')
    ap.add_argument('-ptype', default='interneuron')
    ap.add_argument('-ystep', type=float, default=None)
    ap.add_argument('-xstage', type=float, default=None)
    ap.add_argument('-dsyn', default=2.0, type=float)
    ap.add_argument('-out', default=os.path.join(HERE, 'nesvbp-pong'))
    a = ap.parse_args()
    open(a.out, 'w').write(make(a.variant, a.ptype, a.dsyn, a.ystep, a.xstage))
    print('wrote', a.out)
