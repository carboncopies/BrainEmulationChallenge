"""dp_derive.py: derive every weight of the spiking controller from K and the closed-loop
statistics, write weights_recipe.json. No search, no tuning: each number below is a formula.

Run: python3 dp_derive.py [--n-out N]    (prints the derivation table)

Derivation (T = 10 ms window, tau_e = integral of one unit synaptic conductance, S = dnu/dG
of the output neuron at its operating point Ge0):
 1. K = dlqr(ctrl_dt=10 ms) plain 1x6 gain (the one that holds up to 2 ticks of delay).
 2. Statistics: LQR closed loop, 10 ms, delay 1, disturbance, 180 s, seed 100 (eval seeds
    are 0,1,2): peak |s_i| -> encoder range_i = RANGE_MARGIN * peak_i.
 3. Encoder gain g_i = r0 / range_i  (pos: r0 + g s, neg: r0 - g s, never leaves [0, 2 r0]).
 4. Output operating point: Ge0 such that nu(Ge0) = half the refractory-limited maximum
    1/(t_ref + dt). push and pull both sit there at s = 0.
 5. Linear law: push-pull conductance difference from state i is 2 w_i k_i tau_e g_i s_i,
    force = c n_out T S (that), required = K_i s_i  ->  w_i k_i = |K_i| / (2 C S tau_e g_i)
    with C = c n_out T [N/Hz] (force per Hz of push-minus-pull rate per neuron).
 6. Baseline conductance of the signal populations (all at r0) is sum_i w_i k_i r0 tau_e and
    there is NO bias population, so it must equal Ge0: this fixes C:
        C = sum_i |K_i| range_i / (2 S Ge0)       [then w_i k_i = share_i * Ge0/(r0 tau_e)
                                                    with share_i = |K_i| range_i / sum]
 7. Synapses: k_i = ceil(w_i k_i / W_MAX), w_i = (w_i k_i)/k_i  <= W_MAX nS.
 8. Routing: K_i > 0 (s>0 must pull, force negative): pos -> pull, neg -> push; K_i < 0 swapped.
 9. Output size from a count-noise target: each output neuron's count in a window is
    quasi-regular, variance v = 0.031 per neuron (MEASURED once on the first, oversized build,
    see weightspace_log.md; a regular spike counter would be up to 1/6); sigma_F = c sqrt(2 n_out v) with
    c = C/(n_out T)  ->  n_out = 2 v (C / (T sigma_target))^2.
"""
import argparse
import json
import math
import os

import numpy as np

from dp_env import run, DisturbanceCfg
from dp_lqr import dlqr, StateFeedback
import dp_spiking as sp

HERE = os.path.dirname(os.path.abspath(__file__))
CTRL_DT = 0.01
T_WIN = 0.010
STAT_SEED = 100
STAT_DELAY = 1
RANGE_MARGIN = 1.25
R0_HZ = 150.0
W_MAX_NS = 2.0
N_IN = 256
SIGMA_TARGET_N = 0.25
V_COUNT = 0.031   # measured: zero-state force sd 0.108 N at n_out 595 (first build, c 0.0177) -> v
F_MAX = 20.0
NAMES = ['x', 'th1', 'th2', 'xd', 'th1d', 'th2d']


def stats(T=180.0):
    K = dlqr(ctrl_dt=CTRL_DT)[0]
    m, tr = run(StateFeedback(K), T=T, seed=STAT_SEED, ctrl_dt=CTRL_DT, delay=STAT_DELAY,
                disturbance=DisturbanceCfg(), trace=True)
    S = tr['s'][::2]
    return K.reshape(-1), S.std(0), np.abs(S).max(0), m, tr['F']


def derive(n_out=None, T=180.0, verbose=True):
    P = sp.NEURON
    K, sigma, peak, m, F = stats(T)
    rng_i = RANGE_MARGIN * peak
    g = R0_HZ / rng_i
    # operating point
    nu_cap = 1000.0 / (P['t_ref_ms'] + P['dt_ms'])
    nu0 = nu_cap / 2
    Gs = np.linspace(2.0, 30.0, 280001)
    Ge0 = float(Gs[np.argmin(np.abs(sp.nu_meanfield(Gs) - nu0))])
    h = 1e-4
    S = float((sp.nu_meanfield(Ge0 + h) - sp.nu_meanfield(Ge0 - h))[0] / (2 * h))  # Hz/nS
    tau_e = sp.tau_syn_eff_ms(P)
    Kr = np.abs(K) * rng_i
    # C [N/Hz]: force = C * (nu_push - nu_pull) per neuron-rate; K*range [N], S*Ge0 [Hz]
    C = float(Kr.sum() / (2 * S * Ge0))
    share = Kr / Kr.sum()
    wk = share * Ge0 / (R0_HZ * 1e-3 * tau_e)          # nS summed over synapses per out neuron
    k = np.ceil(wk / W_MAX_NS - 1e-9).astype(int)
    w = wk / k
    if n_out is None:
        n_out = int(math.ceil(2 * V_COUNT * (C / (T_WIN * SIGMA_TARGET_N)) ** 2))
    c = C / (n_out * T_WIN)
    pops = []
    for i in range(6):
        pos_side = 'pull' if K[i] > 0 else 'push'
        neg_side = 'push' if K[i] > 0 else 'pull'
        pops.append(dict(index=i, name=NAMES[i] + '+', side=pos_side, k=int(k[i]), w_nS=float(w[i])))
        pops.append(dict(index=6 + i, name=NAMES[i] + '-', side=neg_side, k=int(k[i]), w_nS=float(w[i])))
    rec = dict(
        note='generated by dp_derive.py; every value is a formula, see its docstring',
        neuron=P, ctrl_dt_s=CTRL_DT, window_ms=T_WIN * 1e3, latency_ticks_assumed=2,
        K=K.tolist(), sigma=sigma.tolist(), peak=peak.tolist(), range_margin=RANGE_MARGIN,
        ranges=rng_i.tolist(), r0_hz=R0_HZ, g_Hz_per_unit=g.tolist(), n_in=N_IN, n_out=n_out,
        Ge0_nS=Ge0, nu0_Hz=nu0, nu_cap_Hz=nu_cap, S_Hz_per_nS=S, tau_e_ms=tau_e,
        C_N_per_Hz=C, c_N_per_spike=c, F_max=F_MAX, w_max_nS=W_MAX_NS,
        K_range_N=Kr.tolist(), pops=pops, connect_seed=12345,
        stat_run=dict(seed=STAT_SEED, T=T, rms_F=float(F.std()), peak_F=float(np.abs(F).max()),
                      metrics=m),
        count_noise_target_N=SIGMA_TARGET_N, count_var_per_neuron=V_COUNT,
        hand_adjustments=[], n_receptors=2 * n_out * int(k.sum()), n_input_neurons=12 * N_IN,
    )
    if verbose:
        print('K        ', np.round(K, 3))
        print('sigma    ', np.round(sigma, 4))
        print('peak     ', np.round(peak, 4), ' peak/sigma', np.round(peak / sigma, 1))
        print('range    ', np.round(rng_i, 4))
        print('K*sigma  ', np.round(np.abs(K) * sigma, 3), 'spread', round(float((np.abs(K) * sigma).max() / (np.abs(K) * sigma).min()), 1))
        print('K*range  ', np.round(Kr, 3), 'spread', round(float(Kr.max() / Kr.min()), 1))
        print('|K| spread', round(float(np.abs(K).max() / np.abs(K).min()), 1), ' g_i Hz/unit', np.round(g, 1))
        print('Ge0 %.3f nS nu0 %.1f Hz S %.2f Hz/nS tau_e %.3f ms' % (Ge0, nu0, S, tau_e))
        print('C = %.4f N/Hz  n_out %d  c = %.5f N/spike' % (C, n_out, c))
        print('w*k nS   ', np.round(wk, 3)); print('k        ', k); print('w nS     ', np.round(w, 3))
        print('synapses per output neuron:', int(k.sum()), ' receptors total:', 2 * n_out * int(k.sum()))
    return rec


def measure_gain(rec, n_states=40, ticks=40, seed=7):
    """ONE measurement: regression slope of decoded force on -K s over static states
    s ~ N(0, (0.5 sigma)^2) (the small-signal regime). Returns slope (1.0 = derived law holds)."""
    rs = np.random.default_rng(seed)
    K = np.array(rec['K'])
    sg = np.array(rec['sigma'])
    want, got = [], []
    ctl = sp.SpikingController(rec, seed=seed)
    for _ in range(n_states):
        s = rs.normal(0, 0.5 * sg)
        for _ in range(8):
            ctl(s)
        f = np.mean([ctl(s) for _ in range(ticks)])
        want.append(float(-K @ s))
        got.append(float(f))
    want, got = np.array(want), np.array(got)
    return float(want @ got / (want @ want)), float(np.sqrt(np.mean((got - want) ** 2)))


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--n-out', type=int, default=None)
    ap.add_argument('--T', type=float, default=180.0)
    ap.add_argument('--no-adjust', action='store_true', help='write the pure derived recipe only')
    a = ap.parse_args()
    rec = derive(a.n_out, a.T)
    with open(os.path.join(HERE, 'weights_recipe_derived.json'), 'w') as f:
        json.dump(rec, f, indent=1)
    ratio, rmse = measure_gain(rec)
    print('derived net: static gain ratio (measured/derived) %.3f, rmse %.3f N' % (ratio, rmse))
    rec['measured_gain_ratio_before'] = ratio
    if not a.no_adjust:
        # HAND ADJUSTMENT A1 (single, reasoned): the derived slope S comes from a continuous
        # closed form, the stand-in updates at 1 ms; rescale the decoder constant by the
        # measured ratio. Weights untouched.
        c0 = rec['c_N_per_spike']
        rec['c_N_per_spike'] = c0 / ratio
        rec['hand_adjustments'].append(dict(id='A1', param='c_N_per_spike', before=c0,
                                            after=c0 / ratio, measured_ratio=ratio))
        r2, rm2 = measure_gain(rec, seed=8)
        rec['measured_gain_ratio_after'] = r2
        print('after A1: ratio %.3f rmse %.3f N' % (r2, rm2))
    with open(os.path.join(HERE, 'weights_recipe.json'), 'w') as f:
        json.dump(rec, f, indent=1)
    print('wrote weights_recipe.json, weights_recipe_derived.json')
