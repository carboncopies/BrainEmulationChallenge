def parse_thresholds(spec):
    th = {}
    for part in spec.split(","):
        t, rng = part.split("=")
        lo, _, hi = rng.partition(":")
        th[t] = {"min": float(lo), "max": float(hi) if hi else None}
    return th


def _show_cfs(cfs, thresholds):
    if cfs.attrs.get("synthetic"):
        print(SYNTHETIC_BANNER)
    cols = [c for c in cfs.columns if not c.startswith("margin_")]
    with pd.option_context("display.width", 250, "display.max_columns", 50, "display.float_format", "{:.1f}".format):
        print(cfs[cols].to_string())


