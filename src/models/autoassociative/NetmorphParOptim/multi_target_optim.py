"""Multi-target Netmorph parameter optimization (RF + conservative DiCE).

Generalizes Marianna Gabrielyan's Phase2_Optim.ipynb (Pyr->Pyr, target
`usable_conns2`) to any number of target columns (Pyr->Int, Int->Pyr,
Int->Int, ...) and adds joint counterfactuals, biological-realism checks
(bio_ranges.json / bio_check.py), a synthetic-label fallback for pipeline
TESTING ONLY, and a `needs_more_samples` report.

Method (same as Phase2): RandomForestRegressor (2000 trees), 95 % prediction
interval = 2.5/97.5 percentiles of the per-tree predictions, and a
"conservative" model that returns the 2.5th percentile. For several targets
we hand DiCE (method='random') ONE scalar: the minimum over targets of
(conservative prediction / required minimum), set to <= 0 whenever the
candidate violates a hard biological constraint.  desired_range=[1, inf)
therefore means "all targets meet their thresholds with ~97.5 % one-sided
confidence AND the parameters are biologically plausible".

CLI examples (run from this directory):
  python multi_target_optim.py train --data Phase1_1500_700_combined_labeled-RS20240628.xlsx --targets usable_conns2
  python multi_target_optim.py optimize --data ... --targets usable_conns2 --thresholds usable_conns2=500:2500
  python multi_target_optim.py synthetic-demo        # SYNTHETIC labels, pipeline test only
  python multi_target_optim.py needs-more --data ... --targets usable_pyr_int,usable_int_pyr,usable_int_int
"""
