# --------------------------------------------------------------------------- data
def load_labeled(path_or_df, targets, filters=None, features=None):
    """Load a labeled xlsx/csv (or DataFrame). Returns (df, features).
    Column names are stripped. Features = BASE_FEATURES present with no NaNs
    (so `interneuron` is included only when the column exists and is filled)."""
    df = path_or_df.copy() if isinstance(path_or_df, pd.DataFrame) else (
        pd.read_excel(path_or_df) if str(path_or_df).endswith("xlsx") else pd.read_csv(path_or_df))
    df = bio_check.clean_columns(df)
    if features is None:
        features = [c for c in BASE_FEATURES if c in df.columns and df[c].notna().any()]
    missing = [t for t in targets if t not in df.columns]
    if missing:
        raise KeyError(f"target column(s) not in data: {missing}; columns = {list(df.columns)}")
    return df, features


def target_rows(df, target, features, filters=None):
    """Rows usable for one target: non-NaN features+label, Marianna-style range filter."""
    filters = {**DEFAULT_FILTERS, **(filters or {})}
    d = df[features + [target]].dropna()
    lo, hi = filters.get(target, (0, np.inf))
    d = d[(d[target] >= lo) & (d[target] <= hi)] if target in DEFAULT_FILTERS or target in (filters or {}) \
        else d[d[target] > 0]
    return d.reset_index(drop=True)


# ------------------------------------------------------------------------ model
def tree_predictions(rf, X):
    """(n_samples, n_trees) per-tree predictions (fast: bypasses per-tree validation)."""
    X32 = np.ascontiguousarray(np.asarray(X, dtype=np.float32))
    return np.stack([np.asarray(t.tree_.predict(X32)).reshape(len(X32), -1)[:, 0] for t in rf.estimators_], axis=1)


class TargetModel:
    """One RF for one target + its 95 % PI and diagnostics."""

    def __init__(self, target, features, n_estimators=2000, random_state=42, filters=None):
        self.target, self.features = target, list(features)
        self.n_estimators, self.random_state, self.filters = n_estimators, random_state, filters
        self.rf, self.metrics = None, {}

    def fit(self, df, min_rows=20):
        d = target_rows(df, self.target, self.features, self.filters)
        self.n_rows = len(d)
        if len(d) < min_rows:
            self.metrics = {"trained": False, "n_rows": len(d),
                            "reason": f"only {len(d)} usable labeled rows (< {min_rows}); not trained"}
            return self
        X, y = d[self.features], d[self.target]
        Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.2, random_state=self.random_state)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            self.rf = RandomForestRegressor(n_estimators=self.n_estimators, bootstrap=True, oob_score=True,
                                            random_state=self.random_state, n_jobs=-1).fit(Xtr, ytr)
        self.X_train, self.y_train, self.X_test, self.y_test = Xtr, ytr, Xte, yte
        tp = tree_predictions(self.rf, Xte)
        lo, hi = np.percentile(tp, 2.5, axis=1), np.percentile(tp, 97.5, axis=1)
        pred = self.rf.predict(Xte)
        self.metrics = {
            "trained": True, "n_rows": len(d), "n_train": len(Xtr), "n_test": len(Xte),
            "oob_r2": float(self.rf.oob_score_), "train_r2": float(self.rf.score(Xtr, ytr)),
            "test_r2": float(r2_score(yte, pred)) if len(yte) > 1 else float("nan"),
            "test_rmse": float(np.sqrt(np.mean((yte - pred) ** 2))),
            "pi95_mean_width_test": float(np.mean(hi - lo)),
            "pi95_coverage_test": float(np.mean((yte >= lo) & (yte <= hi))),
            "note": "PI = 2.5/97.5 percentile of per-tree predictions (model/ensemble spread), "
                    "not a noise-aware predictive interval: coverage of y is expected to be < 95 %.",
        }
        return self

    def pi(self, X, q=(2.5, 50, 97.5)):
        tp = tree_predictions(self.rf, X[self.features])
        return np.percentile(tp, list(q), axis=1).T

    def lower(self, X):
        return self.pi(X, (2.5,))[:, 0]

    def uncertainty(self, X):
        """Per-tree std (ensemble disagreement) - used to pick where to sample next."""
        return tree_predictions(self.rf, X[self.features]).std(axis=1)


class ConservativeModel:
    """DiCE-compatible: predict() -> 2.5th percentile of per-tree predictions (Phase2 notebook)."""

    def __init__(self, tm):
        self.tm = tm

    def predict(self, instances):
        X = instances if isinstance(instances, pd.DataFrame) else pd.DataFrame(instances, columns=self.tm.features)
        return self.tm.lower(X)


class MultiTargetModel:
    def __init__(self, targets, features, n_estimators=2000, filters=None, synthetic=False):
        self.targets, self.features, self.synthetic = list(targets), list(features), synthetic
        self.models = {t: TargetModel(t, features, n_estimators, filters=filters) for t in targets}

    def fit(self, df, min_rows=20):
        for m in self.models.values():
            m.fit(df, min_rows)
        return self

    @property
    def trained(self):
        return [t for t, m in self.models.items() if m.rf is not None]

    def report(self):
        rep = {t: m.metrics for t, m in self.models.items()}
        return {"synthetic_labels": self.synthetic, "features": self.features, "targets": rep}

    # ---- joint margin ----------------------------------------------------
    def margins(self, X, thresholds):
        """Per-target margin = conservative prediction / required minimum (>=1 means met);
        if a max is given, also hi/lower so lower must stay inside [lo, hi]."""
        out = {}
        for t, th in thresholds.items():
            low = self.models[t].lower(X)
            s = low / float(th["min"])
            if th.get("max") not in (None, float("inf")):
                s = np.minimum(s, float(th["max"]) / np.maximum(low, 1e-9))
            out[t] = s
        return pd.DataFrame(out, index=X.index)

    def joint_score(self, X, thresholds, use_bio=True):
        s = self.margins(X, thresholds).min(axis=1).values
        if use_bio:
            ok = bio_check.bio_ok_mask(X)
            s = np.where(ok, s, np.minimum(s, -1.0))
        return s


class JointScoreModel:
    """Scalar wrapper handed to DiCE (see module docstring)."""

    def __init__(self, mtm, thresholds, use_bio=True):
        self.mtm, self.thresholds, self.use_bio = mtm, thresholds, use_bio

    def predict(self, instances):
        X = instances if isinstance(instances, pd.DataFrame) else pd.DataFrame(instances, columns=self.mtm.features)
        return self.mtm.joint_score(X.reset_index(drop=True), self.thresholds, self.use_bio)


# ---------------------------------------------------------------- counterfactuals
def default_permitted_ranges(features, cfg=None):
    cfg = cfg or bio_check.load_ranges()
    return {f: [cfg["parameters"][f]["min"], cfg["parameters"][f]["max"]] for f in features}


def _round_candidates(df, cfg):
    df = df.copy()
    for p, r in cfg["parameters"].items():
        if p in df.columns:
            df[p] = df[p].astype(float).round(0 if r["integer"] else 1)  # dm.weight is sent as %.1f
    return df


def generate_joint_cfs(mtm, thresholds, query=None, total_CFs=8, permitted_range=None,
                       features_to_vary=None, seed=42, method="dice", sample_size=5000):
    """Counterfactual parameter sets meeting ALL thresholds (+ bio hard checks).
    thresholds = {target: {"min": x, "max": y|None}}. Returns DataFrame sorted by
    joint margin, with per-target pred_median / pred_lower / margin and bio columns."""
    import dice_ml
    cfg = bio_check.load_ranges()
    feats = mtm.features
    tm0 = mtm.models[next(iter(thresholds))]
    permitted_range = {**default_permitted_ranges(feats, cfg), **(permitted_range or {})}
    features_to_vary = features_to_vary or feats
    rng = np.random.default_rng(seed)
    if query is None:  # start from the (random) test row with the lowest joint margin among a few
        pool = tm0.X_test[feats].reset_index(drop=True)
        query = pool.iloc[[int(rng.integers(len(pool)))]]
    query = pd.DataFrame([query] if isinstance(query, dict) else query)[feats].astype(float).reset_index(drop=True)

    cands = None
    if method == "dice":   # method="bio_pool" skips DiCE and uses only the bio-feasible random search
        scorer = JointScoreModel(mtm, thresholds)
        train_X = pd.concat([m.X_train[feats] for m in mtm.models.values() if m.rf is not None]
                            ).drop_duplicates().reset_index(drop=True)
        data_df = train_X.copy()
        data_df["joint_score"] = scorer.predict(train_X)
        d = dice_ml.Data(dataframe=data_df, continuous_features=feats, outcome_name="joint_score")
        m = dice_ml.Model(model=scorer, backend="sklearn", model_type="regressor")
        exp = dice_ml.Dice(d, m, method="random")
        try:
            res = exp.generate_counterfactuals(
                query, total_CFs=total_CFs * 3, desired_range=[1.0, 1e9],
                permitted_range={k: [float(v[0]), float(v[1])] for k, v in permitted_range.items()},
                features_to_vary=features_to_vary, random_seed=seed, sample_size=sample_size)
            cands = res.cf_examples_list[0].final_cfs_df
            cands = cands[feats] if cands is not None else None
        except Exception as e:  # DiCE raises when it finds nothing
            print(f"[generate_joint_cfs] DiCE found no CFs ({type(e).__name__}: {e}); using bio-feasible random search instead")
    # Supplement (or replace, if DiCE found nothing) with a bio-feasible random search: the
    # uniform box is mostly biologically implausible (see bio_report), so DiCE's uniform sampler
    # often finds nothing once the hard bio constraints are applied.
    pool = _lhs_bio_candidates(20000, seed, cfg)
    for f in feats:
        if f in pool.columns:
            pool = pool[pool[f].between(permitted_range[f][0], permitted_range[f][1])]
        if f not in features_to_vary:
            pool[f] = float(query[f].iloc[0])
    pool = pool[[f for f in feats if f in pool.columns]]
    if all(f in pool.columns for f in feats):
        cands = pool if cands is None else pd.concat([cands, pool], ignore_index=True)
    if cands is None or len(cands) == 0:
        raise RuntimeError("no candidate parameter sets inside the permitted ranges satisfy the bio constraints")
    cands = _round_candidates(cands.reset_index(drop=True), cfg)
    cands = cands.drop_duplicates().reset_index(drop=True)
    # re-score AFTER rounding; keep only those satisfying everything
    mar = mtm.margins(cands, thresholds)
    bio = bio_check.check_frame(cands, cfg)
    out = pd.concat([cands, mar.add_prefix("margin_")], axis=1)
    for t in thresholds:
        q = mtm.models[t].pi(cands)
        out[f"{t}__pred_median"], out[f"{t}__pred_lower"] = q[:, 1], q[:, 0]
    out["joint_margin"] = mar.min(axis=1).values
    out["bio_hard_violations"] = bio["bio_hard_violations"].values
    out["bio_soft_violations"] = bio["bio_soft_violations"].values
    out["density_per_mm3"] = bio["density_per_mm3"].values
    out["pyramidal_fraction"] = bio["pyramidal_fraction"].values
    out["interneuron_imputed"] = bio["interneuron_imputed"].values
    ok = out[(out.joint_margin >= 1.0) & (out.bio_hard_violations == 0)]
    ok = ok.sort_values(["bio_soft_violations", "joint_margin"], ascending=[True, False])
    # diversity: greedy, drop near-duplicates in standardized space
    chosen, span = [], np.array([permitted_range[f][1] - permitted_range[f][0] for f in feats], float)
    for i, r in ok.iterrows():
        v = r[feats].values.astype(float) / span
        if all(np.linalg.norm(v - c) > 0.08 for c in chosen):
            chosen.append(v)
            if len(chosen) == total_CFs:
                break
        else:
            ok = ok.drop(i)
    ok = ok.iloc[:total_CFs].copy()
    ok.attrs.update(query=query.iloc[0].to_dict(), synthetic=mtm.synthetic, n_rejected_after_rounding_or_bio=int(len(out) - len(ok)))
    return ok.reset_index(drop=True)


# ------------------------------------------------------------- synthetic fallback
def make_synthetic_labels(df, seed=0):
    """SYNTHETIC labels for Pyr->Int, Int->Pyr, Int->Int. Made-up monotone formula
    (counts ~ n_src*n_tgt, mild dependence on dm.weight, days, region size, lognormal
    noise). Purpose: exercise the pipeline end-to-end. Carries NO biological or Netmorph
    information. Requires an `interneuron` column."""
    df = bio_check.clean_columns(df)
    if "interneuron" not in df.columns:
        raise ValueError("synthetic labels need an 'interneuron' column")
    rng = np.random.default_rng(seed)
    r, t, w, dd = df["shape.radius"] / 150.0, df["shape.thickness"] / 35.0, df["dm.weight"], df["days"] / 22.0

    def lab(src, tgt, wexp, k):
        raw = src * tgt * (w ** wexp) * dd ** 2 / (r * np.sqrt(t)) * k
        return np.round(raw * rng.lognormal(0, 0.15, len(df))).astype(int)

    out = df.copy()
    p, i = out["pyramidal"], out["interneuron"]
    out["usable_pyr_int"] = lab(p, i, 0.5, 1)
    out["usable_int_pyr"] = lab(i, p, 0.8, 1)
    out["usable_int_int"] = lab(i, i, 0.3, 1)
    for c in ("usable_pyr_int", "usable_int_pyr", "usable_int_int"):   # rescale: median ~ 700
        out[c] = np.round(out[c] * 700.0 / max(out[c].median(), 1)).astype(int)
    out["_SYNTHETIC_LABELS"] = True
    out.attrs["synthetic"] = True
    return out


# --------------------------------------------------------- needs_more_samples
def _lhs_bio_candidates(n, seed=0, cfg=None):
    """Latin-hypercube candidates over the 7 HARD parameter ranges (team limits). Density and pyramidal
    fraction are WARNINGS only and not enforced here. dm.weight is rounded to 1 decimal because
    gen_autonm_labels.py sends it with %.1f. Asserts every row is within the hard limits."""
    from scipy.stats import qmc
    cfg = cfg or bio_check.load_ranges()
    P = cfg["parameters"]
    names = ["days", "pyramidal", "interneuron", "minneuronseparation", "shape.radius", "shape.thickness", "dm.weight"]
    u = qmc.LatinHypercube(d=7, seed=seed).random(n)
    df = pd.DataFrame({k: P[k]["min"] + u[:, c] * (P[k]["max"] - P[k]["min"]) for c, k in enumerate(names)})
    for k in names:
        df[k] = df[k].round(1) if k == "dm.weight" else df[k].round(0)
    df = df.clip(lower={k: P[k]["min"] for k in names}, upper={k: P[k]["max"] for k in names}, axis=1)
    bio_check.assert_hard_limits(df, cfg)
    return df.reset_index(drop=True)


def learning_curve(df, target, features, sizes=(50, 100, 200, 400, 800, 1600), n_estimators=200, seed=0):
    d = target_rows(df, target, features)
    rows = []
    for s in sizes:
        if s > len(d):
            break
        sub = d.sample(s, random_state=seed)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            pred = cross_val_predict(RandomForestRegressor(n_estimators=n_estimators, random_state=seed, n_jobs=-1),
                                     sub[features], sub[target], cv=KFold(5, shuffle=True, random_state=seed))
        rows.append({"n": s, "cv_r2": float(r2_score(sub[target], pred))})
    return rows


def needs_more_samples(df, targets, features, mtm=None, reference_df=None, reference_target="usable_conns2",
                       n_suggest=100, out_xlsx=None, seed=0, target_fraction_of_plateau=0.95):
    """Report how many Netmorph runs are needed for each target and where to run them.
    * per-target status from the labeled data;
    * learning curve on the reference (Pyr->Pyr, the only target with ~2000 labels) to estimate
      how many USABLE labels give R^2 within 5 % of plateau;
    * runs = usable labels needed / usable-label yield (observed, else the reference yield);
    * suggested parameter sets: bio-feasible LHS pool ranked by RF ensemble uncertainty and by
      distance from already-labeled rows (greedy farthest-point)."""
    cfg = bio_check.load_ranges()
    ref_df = reference_df if reference_df is not None else df
    ref_feats = [f for f in features if f in ref_df.columns and ref_df[f].notna().any()]
    ref_tm = None
    lc = []
    if reference_target in ref_df.columns:
        lc = learning_curve(ref_df, reference_target, ref_feats)
        raw_ref = ref_df[reference_target].notna().sum()
        ref_yield = len(target_rows(ref_df, reference_target, ref_feats)) / max(raw_ref, 1)
    else:
        ref_yield = 0.5
    plateau = max([r["cv_r2"] for r in lc], default=float("nan"))
    n_needed = next((r["n"] for r in lc if r["cv_r2"] >= target_fraction_of_plateau * plateau), None) if lc else None
    n_needed_floor = max(n_needed or 0, 10 * len(features), 200)
    report = {"reference_learning_curve": lc, "reference_plateau_cv_r2": plateau,
              "usable_labels_needed_estimate": int(n_needed_floor),
              "estimate_basis": f"smallest learning-curve size on {reference_target} with CV R^2 >= {target_fraction_of_plateau:.0%} of "
                                f"plateau, floored at max(10*n_features, 200). Assumes the new targets are about as learnable as Pyr->Pyr (an assumption).",
              "targets": {}}
    for t in targets:
        raw = int(df[t].notna().sum()) if t in df.columns else 0
        usable = len(target_rows(df, t, features)) if t in df.columns else 0
        y_obs = usable / raw if raw >= 20 else None
        yield_used = y_obs if y_obs else ref_yield
        total_runs = math.ceil(n_needed_floor / max(yield_used, 0.05))
        have = usable
        report["targets"][t] = {
            "n_labeled_rows": raw, "n_usable_rows": usable,
            "usable_yield_used": round(float(yield_used), 3),
            "yield_source": "observed" if y_obs else f"assumed = Pyr->Pyr yield ({ref_yield:.2f}); too few labeled rows to observe",
            "additional_netmorph_runs_recommended": max(total_runs - raw, 0),
            "total_runs_target": total_runs,
            "sufficient_now": bool(have >= n_needed_floor)}
    # --- where to sample
    pool = _lhs_bio_candidates(20000, seed, cfg)
    unc = np.zeros(len(pool))
    sources = []
    for t in targets:
        tm = mtm.models.get(t) if mtm else None
        if tm is not None and tm.rf is not None:
            unc += tm.uncertainty(pool) / max(tm.y_train.mean(), 1)
            sources.append(f"{t}: own RF")
    if not sources:  # proxy: Pyr->Pyr RF on shared features
        ref_tm = TargetModel(reference_target, ref_feats, n_estimators=300).fit(ref_df)
        if ref_tm.rf is not None:
            unc = ref_tm.uncertainty(pool) / max(ref_tm.y_train.mean(), 1)
            sources.append(f"proxy: Pyr->Pyr RF ({reference_target}) on features {ref_feats}; "
                           "new targets have too few labels for their own RF")
    allf = [f for f in BASE_FEATURES if f in pool.columns]
    lo = np.array([cfg["parameters"][f]["min"] for f in allf], float)
    span = np.array([cfg["parameters"][f]["max"] - cfg["parameters"][f]["min"] for f in allf], float)
    Z = (pool[allf].values - lo) / span
    have_rows = df[[f for f in allf if f in df.columns]].dropna()
    if len(have_rows) and set(allf) <= set(have_rows.columns):
        H = (have_rows[allf].values - lo) / span
        dist = np.array([np.min(np.linalg.norm(H - z, axis=1)) for z in Z[:: max(1, len(Z) // 4000)]])
        dist = np.interp(np.arange(len(Z)), np.arange(len(Z))[:: max(1, len(Z) // 4000)], dist)
    else:
        dist = np.ones(len(Z))
    rk = lambda a: pd.Series(a).rank(pct=True).values
    score = rk(unc) + rk(dist)
    sel, mind = [], np.full(len(Z), np.inf)
    order_pool = np.argsort(-score)[:3000]
    for _ in range(min(n_suggest, len(order_pool))):
        cand = order_pool[np.argmax(score[order_pool] * (np.minimum(mind[order_pool], 1.0) + 1e-3))]
        sel.append(cand)
        mind = np.minimum(mind, np.linalg.norm(Z - Z[cand], axis=1))
    sug = pool.iloc[sel].copy()
    sug["dm.weight "] = sug.pop("dm.weight")  # Phase0 input files use the trailing-space name
    sug = sug[["days", "pyramidal", "interneuron", "minneuronseparation", "shape.radius", "shape.thickness", "dm.weight "]]
    bio_check.assert_hard_limits(sug)   # suggestions must never leave the hard limits
    hi = pool.iloc[np.argsort(-unc)[: max(len(pool) // 10, 1)]]
    report["uncertainty_source"] = sources
    report["high_uncertainty_region_top_decile_of_bio_feasible_pool"] = {
        c: [float(hi[c].quantile(.1)), float(hi[c].median()), float(hi[c].quantile(.9))] for c in allf}
    report["high_uncertainty_region_note"] = "[10th pct, median, 90th pct] of the most uncertain 10 % of 20000 bio-feasible candidates"
    report["bio_feasible_fraction_of_phase0_style_box"] = "see bio_report(); pool is generated inside the bio window directly"
    report["suggested_parameter_sets"] = len(sug)
    if out_xlsx:
        sug.to_excel(out_xlsx, index=False)
        report["suggested_parameter_sets_file"] = out_xlsx
    return report, sug


def bio_report(df):
    """How much of a dataset is biologically plausible under bio_ranges.json?"""
    r = bio_check.check_frame(df)
    out = {"n": len(r), "frac_bio_ok": float(r.bio_ok.mean()),
           "frac_density_warning": float(r.warn_density.mean()),
           "frac_pyr_fraction_warning": float(r.warn_pyr_fraction.mean()),
           "interneuron_imputed": bool(r.interneuron_imputed.iloc[0]),
           "density_per_mm3_pctiles_5_50_95": [float(x) for x in r.density_per_mm3.quantile([.05, .5, .95])]}
    if "warn_separation_vs_soma" in r:
        out["frac_soft_separation_violation"] = float(r.warn_separation_vs_soma.mean())
    return out


